#!/usr/bin/env python3
"""Generate src/XRay.OneNote/Internal/Pdf/StandardFontMetrics.g.cs.

Writes the advance widths of the twelve Latin PDF standard fonts (Helvetica, Times and Courier
families) for every WinAnsiEncoding code. The widths are Adobe's Core 14 AFM metrics, read here
from the copies the ReportLab toolkit ships (`pip install reportlab`). Run it only to regenerate
the table; the output is committed.
"""

from __future__ import annotations

import importlib
from pathlib import Path

FONTS = {
    "Helvetica": "helvetica",
    "Helvetica-Bold": "helveticabold",
    "Helvetica-Oblique": "helveticaoblique",
    "Helvetica-BoldOblique": "helveticaboldoblique",
    "Times-Roman": "timesroman",
    "Times-Bold": "timesbold",
    "Times-Italic": "timesitalic",
    "Times-BoldItalic": "timesbolditalic",
    "Courier": "courier",
    "Courier-Bold": "courierbold",
    "Courier-Oblique": "courieroblique",
    "Courier-BoldOblique": "courierboldoblique",
}

OUT = Path(__file__).resolve().parent.parent / "src" / "XRay.OneNote" / "Internal" / "Pdf" / "StandardFontMetrics.g.cs"


def main() -> None:
    encoding = importlib.import_module("reportlab.pdfbase._fontdata_enc_winansi").WinAnsiEncoding
    lines = [
        "// <auto-generated>",
        "// Generated by tools/generate_standard_font_metrics.py. Advance widths (1/1000 em) of the PDF",
        "// standard fonts for each WinAnsiEncoding code, from Adobe's Core 14 AFM metrics.",
        "// </auto-generated>",
        "",
        "namespace XRay.OneNote.Internal.Pdf;",
        "",
        "internal static partial class StandardFontMetrics",
        "{",
        "    private static readonly Dictionary<string, short[]> WidthTables = new(StringComparer.Ordinal)",
        "    {",
    ]
    for name, module in FONTS.items():
        widths = importlib.import_module(f"reportlab.pdfbase._fontdata_widths_{module}").widths
        row = [widths.get(glyph, 0) if glyph else 0 for glyph in encoding]
        lines.append(f'        ["{name}"] =')
        lines.append("        [")
        for start in range(0, 256, 16):
            lines.append("            " + ", ".join(str(w) for w in row[start : start + 16]) + ",")
        lines.append("        ],")
    lines += ["    };", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
